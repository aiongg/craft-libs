/// Compares `files` with the dump directory, or rewrites it with `UPDATE_DUMPS=1`. Files in the
/// directory that no longer belong to a dump are reported (and removed on update).
fn check_dir(dir: &Path, files: &[(String, String)]) {
    let update = std::env::var_os("UPDATE_DUMPS").is_some_and(|v| v != "0");
    let names: BTreeSet<&str> = files.iter().map(|(n, _)| n.as_str()).collect();
    let stale: Vec<PathBuf> = std::fs::read_dir(dir)
        .map(|entries| {
            entries
                .filter_map(Result::ok)
                .map(|e| e.path())
                .filter(|p| p.file_name().and_then(|n| n.to_str()).is_some_and(|n| !names.contains(n)))
                .collect()
        })
        .unwrap_or_default();

    if update {
        std::fs::create_dir_all(dir).unwrap();
        for (name, text) in files {
            let path = dir.join(name);
            if std::fs::read_to_string(&path).ok().as_deref() != Some(text) {
                std::fs::write(&path, text).unwrap();
            }
        }
        for path in stale {
            std::fs::remove_file(path).unwrap();
        }
        return;
    }

    let mut report = String::new();
    let mut failed = 0;
    for (name, text) in files {
        let path = dir.join(name);
        match std::fs::read_to_string(&path) {
            Ok(old) if old == *text => {}
            Ok(old) => {
                failed += 1;
                if failed <= 3 {
                    let _ = writeln!(report, "{name}:\n{}", diff(&old, text));
                }
            }
            Err(_) => {
                failed += 1;
                let _ = writeln!(report, "{name}: missing");
            }
        }
    }
    for path in &stale {
        failed += 1;
        let _ = writeln!(report, "{}: no longer generated", path.display());
    }
    assert!(failed == 0, "{failed} token dump(s) differ; rerun with UPDATE_DUMPS=1 to rewrite them and review the diff\n{report}");
}

/// The lines only in `old` (`-`) and only in `new` (`+`), at most 20.
fn diff(old: &str, new: &str) -> String {
    let (a, b): (BTreeSet<&str>, BTreeSet<&str>) = (old.lines().collect(), new.lines().collect());
    let removed = old.lines().filter(|l| !b.contains(l)).map(|l| format!("- {l}"));
    let added = new.lines().filter(|l| !a.contains(l)).map(|l| format!("+ {l}"));
    let all: Vec<String> = removed.chain(added).collect();
    let mut out: Vec<String> = all.iter().take(20).cloned().collect();
    if all.len() > 20 {
        out.push(format!("… {} more", all.len() - 20));
    }
    out.join("\n")
}

fn badge_lines(out: &mut Lines, b: &BadgeTokens) {
    out.line("badge.height", len(b.height));
    out.line("badge.pad_y", len(b.pad_y));
    out.line("badge.pad_x", len(b.pad_x));
    out.line("badge.radius", len(b.radius));
    out.line("badge.label", role(b.label));
    for tone in BadgeTone::ALL {
        for style in BadgeStyle::ALL {
            let colors = b.colors(tone, style);
            for part in BadgePart::ALL {
                out.line(&format!("badge.{}.{}.{}", tone.name(), style.name(), part.name()), hex(colors.part(part)));
            }
        }
    }
}

