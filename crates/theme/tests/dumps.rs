//! Token dumps: every token of every built-in, as text under `tests/dumps/tokens/`, so a change
//! to derivation or a theme file shows up as a reviewable diff.
//!
//! One file per built-in, mode it has, contrast and size, at the default text size. Run
//! `UPDATE_DUMPS=1 cargo test -p craft-theme dump` to rewrite them.
//!
//! The struct destructuring below is exhaustive on purpose: a new token or component field
//! doesn't compile until it is dumped.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use craft_theme::{
    Appearance, BadgePart, BadgeStyle, BadgeTokens, BadgeTone, BarSizes, BorderColors, ButtonColors, ButtonTokens, BySize, CheckOffColors,
    CheckOnColors, CheckTokens, ColorToken, ComponentTokens, Contrast, ContrastCheck, ControlSizes, Dimmed, Easing, Edge, Elevation, ElevationTokens,
    FieldTokens, FontSlot, Gaps, HandleTokens, IconButtonTokens, IconSizes, ItemColors, KbdTokens, ListboxTokens, Mode, Motion, MotionTokens, Pads,
    ProgressTokens, PropertyTokens, RadiusSet, RailSizes, Rgba, SegmentedTokens, ShapeTokens, Size, SizeTokens, SliderTokens, SpaceTokens, States,
    SwatchColor, SwatchTokens, TextSize, ThemeDef, ThumbColors, ToggleButtonTokens, Tokens, TooltipTokens, TypeRole, TypeStyle, TypeTokens, Variants,
    builtins, resolve,
};

const HEADER: &str = "# Generated by crates/theme/tests/dumps.rs; rewrite with UPDATE_DUMPS=1 cargo test -p craft-theme dump";

#[test]
fn token_dumps() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/dumps/tokens");
    let mut files = Vec::new();
    for theme in builtins() {
        for mode in modes(theme) {
            for contrast in [Contrast::Standard, Contrast::High] {
                for size in [Size::Compact, Size::Comfortable] {
                    let appearance = Appearance { mode, contrast, size, text_size: TextSize::Default, reduced_motion: false };
                    let resolved = resolve(theme, appearance, None);
                    let name = format!("{}-{}-{}-{}.txt", short_name(theme), mode_name(mode), contrast_name(contrast), size_name(size));
                    files.push((name, dump(&resolved.tokens, &resolved.warnings)));
                }
            }
        }
    }
    check_dir(&dir, &files);
}

/// The modes a built-in has: single-variant themes dump only theirs.
fn modes(theme: &ThemeDef) -> Vec<Mode> {
    match theme.variants {
        Variants::Both => vec![Mode::Light, Mode::Dark],
        Variants::LightOnly => vec![Mode::Light],
        Variants::DarkOnly => vec![Mode::Dark],
    }
}

fn short_name(theme: &ThemeDef) -> &str {
    let id = theme.id.as_str();
    id.strip_prefix("craft.").unwrap_or(id)
}

fn mode_name(mode: Mode) -> &'static str {
    match mode {
        Mode::Light => "light",
        Mode::Dark => "dark",
    }
}

fn contrast_name(contrast: Contrast) -> &'static str {
    match contrast {
        Contrast::Standard => "standard",
        Contrast::High => "high",
    }
}

fn size_name(size: Size) -> &'static str {
    match size {
        Size::Compact => "compact",
        Size::Comfortable => "comfortable",
    }
}

/// Ordered `key = value` lines.
#[derive(Default)]
struct Lines(String);

impl Lines {
    fn line(&mut self, key: &str, value: impl std::fmt::Display) {
        let _ = writeln!(self.0, "{key} = {value}");
    }
}

/// `#rrggbbaa`, alpha always written.
fn hex(c: Rgba) -> String {
    let [r, g, b, a] = c.0;
    format!("#{r:02x}{g:02x}{b:02x}{a:02x}")
}

/// A length with up to two decimals.
fn len(v: f32) -> String {
    decimals(v, 2)
}

/// `v` with up to `places` decimals, trailing zeros dropped.
fn decimals(v: f32, places: usize) -> String {
    let s = format!("{v:.places$}");
    let s = if s.contains('.') { s.trim_end_matches('0').trim_end_matches('.') } else { &s };
    if s == "-0" { "0".to_owned() } else { s.to_owned() }
}

fn dump(tokens: &Tokens, warnings: &[ContrastCheck]) -> String {
    let mut out = Lines::default();
    out.0.push_str(HEADER);
    out.0.push('\n');

    let Tokens { color, shape, space, size, typography, elevation, motion, component } = tokens;
    for &token in ColorToken::ALL {
        out.line(token.path(), hex(color.get(token)));
    }
    shape_lines(&mut out, shape);
    space_lines(&mut out, space);
    size_lines(&mut out, size);
    type_lines(&mut out, typography);
    elevation_lines(&mut out, elevation);
    motion_lines(&mut out, motion);
    component_lines(&mut out, component);

    for w in warnings {
        let ContrastCheck { fg, bg, ratio, minimum } = w;
        out.line("warning", format!("{} on {}: {ratio:.2} < {minimum:.2}", fg.path(), bg.path()));
    }
    out.0
}

fn edge(e: Edge) -> String {
    match e {
        Edge::Flat => "flat".to_owned(),
        Edge::Bevel { light, dark, width } => format!("bevel {} {} {}", hex(light), hex(dark), len(width)),
    }
}

fn shape_lines(out: &mut Lines, shape: &ShapeTokens) {
    let ShapeTokens { radius, edge: e } = shape;
    let RadiusSet { control, popup, window, panel, button } = radius;
    for (k, v) in [("control", control), ("popup", popup), ("window", window), ("panel", panel), ("button", button)] {
        out.line(&format!("shape.radius.{k}"), len(*v));
    }
    out.line("shape.edge", edge(*e));
}

fn space_lines(out: &mut Lines, space: &SpaceTokens) {
    let SpaceTokens { gap, pad } = space;
    let Gaps { inline, stack, section } = gap;
    for (k, v) in [("inline", inline), ("stack", stack), ("section", section)] {
        out.line(&format!("space.gap.{k}"), len(*v));
    }
    let Pads { control, panel, dialog } = pad;
    for (k, v) in [("control", control), ("panel", panel), ("dialog", dialog)] {
        out.line(&format!("space.pad.{k}"), len(*v));
    }
}

fn size_lines(out: &mut Lines, size: &SizeTokens) {
    let SizeTokens { control, icon, rail, bar, panel_header } = size;
    let ControlSizes { sm, md } = control;
    out.line("size.control.sm", len(*sm));
    out.line("size.control.md", len(*md));
    let IconSizes { sm, md, lg } = icon;
    out.line("size.icon.sm", len(*sm));
    out.line("size.icon.md", len(*md));
    out.line("size.icon.lg", len(*lg));
    let RailSizes { width, button } = rail;
    out.line("size.rail.width", len(*width));
    out.line("size.rail.button", len(*button));
    let BarSizes { title, tab, status, options } = bar;
    for (k, v) in [("title", title), ("tab", tab), ("status", status), ("options", options)] {
        out.line(&format!("size.bar.{k}"), len(*v));
    }
    out.line("size.panel_header", len(*panel_header));
}

fn slot(s: FontSlot) -> &'static str {
    match s {
        FontSlot::Ui => "ui",
        FontSlot::UiSemibold => "ui_semibold",
        FontSlot::Mono => "mono",
    }
}

fn role(r: TypeRole) -> &'static str {
    match r {
        TypeRole::Caption => "caption",
        TypeRole::Label => "label",
        TypeRole::Body => "body",
        TypeRole::BodyStrong => "body_strong",
        TypeRole::Title => "title",
        TypeRole::Heading => "heading",
        TypeRole::Mono => "mono",
    }
}

fn type_lines(out: &mut Lines, t: &TypeTokens) {
    let TypeTokens { caption, label, body, body_strong, title, heading, mono } = t;
    let roles = [
        ("caption", caption),
        ("label", label),
        ("body", body),
        ("body_strong", body_strong),
        ("title", title),
        ("heading", heading),
        ("mono", mono),
    ];
    for (k, style) in roles {
        let TypeStyle { size, line_height, font } = style;
        out.line(&format!("typography.{k}.size"), len(*size));
        out.line(&format!("typography.{k}.line_height"), len(*line_height));
        out.line(&format!("typography.{k}.font"), slot(*font));
    }
}

fn elevation_lines(out: &mut Lines, e: &ElevationTokens) {
    let ElevationTokens { popup, dialog, floating, knob } = e;
    for (k, level) in [("popup", popup), ("dialog", dialog), ("floating", floating), ("knob", knob)] {
        let Elevation { offset: [x, y], blur, spread, alpha } = level;
        out.line(&format!("elevation.{k}.offset"), format!("{} {}", len(*x), len(*y)));
        out.line(&format!("elevation.{k}.blur"), len(*blur));
        out.line(&format!("elevation.{k}.spread"), len(*spread));
        out.line(&format!("elevation.{k}.alpha"), decimals(*alpha, 3));
    }
}

fn easing(e: Easing) -> &'static str {
    match e {
        Easing::Standard => "standard",
        Easing::Enter => "enter",
        Easing::Exit => "exit",
    }
}

fn motion_lines(out: &mut Lines, m: &MotionTokens) {
    let MotionTokens { hover, open, r#move } = m;
    for (k, motion) in [("hover", hover), ("open", open), ("move", r#move)] {
        let Motion { millis, easing: e } = motion;
        out.line(&format!("motion.{k}.millis"), millis);
        out.line(&format!("motion.{k}.easing"), easing(*e));
    }
}

fn by_size(out: &mut Lines, key: &str, v: &BySize<f32>) {
    let BySize { sm, md } = v;
    out.line(&format!("{key}.sm"), len(*sm));
    out.line(&format!("{key}.md"), len(*md));
}

