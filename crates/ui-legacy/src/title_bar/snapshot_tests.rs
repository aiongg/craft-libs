//! Text dumps of the caption buttons' painted shapes, compared with
//! `tests/dumps/title_bar/*.txt` (`UPDATE_DUMPS=1` rewrites them), and the buttons' accessibility.

use craft_theme::Mode;
use craft_window::Layout;
use egui::epaint::{ColorMode, Shape};
use egui::{Context, Event, Pos2, RawInput, Rect, Vec2, pos2, vec2};

use super::captions::{Look, paint, place};
use super::*;
use crate::testing::dump::{Dump, DumpValue as _};
use crate::theme::{Base, Tokens, TokensOf as _, install, scope};

const CELL: Vec2 = vec2(160.0, 32.0);
const HEADER: &str = "Generated by crates/ui/src/title_bar/snapshot_tests.rs; rewrite with UPDATE_DUMPS=1 cargo test -p craft-ui --features window-frame --lib title_bar";

fn path(name: &str) -> String {
    format!("{}/tests/dumps/title_bar/{name}.txt", env!("CARGO_MANIFEST_DIR"))
}

fn at(p: Pos2) -> String {
    format!("{} {}", p.x.dump_value(), p.y.dump_value())
}

/// One line per painted shape: the kind, its geometry and its colours.
fn describe(shape: &Shape, out: &mut Vec<String>) {
    match shape {
        Shape::Vec(shapes) => shapes.iter().for_each(|s| describe(s, out)),
        Shape::Rect(r) => out.push(format!(
            "rect {}..{} radius {} fill {} stroke {}",
            at(r.rect.min),
            at(r.rect.max),
            r.corner_radius.dump_value(),
            r.fill.dump_value(),
            r.stroke.dump_value()
        )),
        Shape::Circle(c) => out.push(format!(
            "circle {} radius {} fill {} stroke {}",
            at(c.center),
            c.radius.dump_value(),
            c.fill.dump_value(),
            c.stroke.dump_value()
        )),
        Shape::LineSegment { points, stroke } => out.push(format!("line {} to {} stroke {}", at(points[0]), at(points[1]), stroke.dump_value())),
        Shape::Path(p) => {
            let colour = match p.stroke.color {
                ColorMode::Solid(c) => c.dump_value(),
                ColorMode::UV(_) => "uv".to_owned(),
            };
            let points: Vec<String> = p.points.iter().map(|&q| at(q)).collect();
            out.push(format!(
                "{} {} fill {} stroke {}@{colour}",
                if p.closed { "polygon" } else { "polyline" },
                points.join(" | "),
                p.fill.dump_value(),
                p.stroke.width.dump_value()
            ));
        }
        other => out.push(format!("{other:?}")),
    }
}

/// The shapes `show` paints in one pass of a window at 2 pixels per point.
fn shapes_of(events: Vec<Event>, show: impl FnMut(&mut egui::Ui)) -> Vec<String> {
    let ctx = Context::default();
    install(&ctx, &Base::suite_default());
    ctx.set_pixels_per_point(2.0);
    let mut show = show;
    let mut run = |events: Vec<Event>| {
        let input = RawInput { screen_rect: Some(Rect::from_min_size(Pos2::ZERO, vec2(2.0 * CELL.x, 5.0 * CELL.y))), events, ..Default::default() };
        let mut out = ctx.run_ui(input, &mut show);
        // No renderer here to take the font atlas.
        out.textures_delta.clear();
        out
    };
    run(vec![]);
    let out = run(events);
    let mut lines = Vec::new();
    out.shapes.iter().for_each(|s| describe(&s.shape, &mut lines));
    lines
}

fn rows() -> [(&'static str, Look); 5] {
    let rest = Look { active: true, ..Look::default() };
    [
        ("rest", rest),
        ("hover", Look { hovered: true, ..rest }),
        ("pressed", Look { hovered: true, pressed: true, ..rest }),
        ("inactive", Look { active: false, ..rest }),
        ("maximized", Look { maximized: true, ..rest }),
    ]
}

/// Every button of every family, in each mode and state: minimize, maximize, close.
#[test]
fn title_bar_caption_dump() {
    let mut dump = Dump::new();
    dump.comment(HEADER);
    for (family, name) in [
        (CaptionFamily::Windows, "windows"),
        (CaptionFamily::Adwaita, "adwaita"),
        (CaptionFamily::Breeze, "breeze"),
        (CaptionFamily::Generic, "generic"),
    ] {
        for (mode, mode_name) in [(Mode::Light, "light"), (Mode::Dark, "dark")] {
            for (row, look) in rows() {
                let bar = Rect::from_min_size(Pos2::ZERO, CELL);
                let sides = (vec![], vec![Caption::Minimize, Caption::Maximize, Caption::Close]);
                let lines = shapes_of(vec![], |ui| {
                    scope(
                        ui,
                        |o| o.mode = Some(mode),
                        |ui| {
                            let style = TitleBar::style(&Tokens::of(ui));
                            for (c, r, centre) in place(family, &sides, bar, bar.left(), bar.right()) {
                                paint(ui, family, c, r, centre, look, look.level(), &style, None);
                            }
                        },
                    );
                });
                dump.group(&format!("{name}.{mode_name}.{row}"), |d| {
                    for (i, line) in lines.iter().enumerate() {
                        d.line(&format!("{i:02}"), line.as_str());
                    }
                });
            }
        }
    }
    dump.check(path("captions"));
}

/// A whole bar in a right-to-left UI: the Windows captions at the left, Close hovered.
#[test]
fn title_bar_right_to_left_dump() {
    let frame = Frame::Integrated(Captions { family: CaptionFamily::Windows, layout: Layout::default() });
    let close = Rect::from_min_size(pos2(0.0, 0.0), vec2(WINDOWS_BUTTON_WIDTH, CELL.y)).center();
    let lines = shapes_of(vec![Event::PointerMoved(close)], |ui| {
        crate::direction::apply(ui.ctx(), crate::direction::Direction::Rtl);
        TitleBar::new(&frame).show(ui, |ui, slots| {
            // The app's content, at the reading start of its slot.
            let pill = Rect::from_min_size(pos2(slots.content.right() - 90.0, slots.centre_line - 8.0), vec2(80.0, 16.0));
            ui.painter().rect_filled(pill, 4.0, egui::Color32::from_rgb(0x00, 0x5F, 0xB8));
        });
    });
    let mut dump = Dump::new();
    dump.comment(HEADER);
    for (i, line) in lines.iter().enumerate() {
        dump.line(&format!("{i:02}"), line.as_str());
    }
    dump.check(path("right_to_left"));
}

#[cfg(all(feature = "screen-testing", not(target_arch = "wasm32")))]
#[test]
fn title_bar_captions_are_labelled_buttons() {
    use egui::accesskit::Role;
    use egui_kittest::Harness;
    use egui_kittest::kittest::Queryable as _;

    let frame = Frame::Integrated(Captions { family: CaptionFamily::Adwaita, layout: Layout::default() });
    let labels = CaptionLabels::default().localized(|key| (key == "window.close").then(|| "Fermer".to_owned()));
    let mut harness = Harness::builder().with_size(vec2(400.0, CELL.y)).build_ui_state(
        move |ui, closed: &mut bool| {
            *closed |= TitleBar::new(&frame).labels(&labels).show(ui, |_, _| {}).close_requested;
        },
        false,
    );
    harness.run();
    // `get_by_*` panics unless exactly one node matches.
    for label in ["Minimize", "Maximize", "Fermer"] {
        let _ = harness.get_by_role_and_label(Role::Button, label);
    }
    harness.input_mut().viewports.entry(egui::ViewportId::ROOT).or_default().maximized = Some(true);
    harness.run();
    let _ = harness.get_by_label("Restore");
    // Like the OS's own caption buttons, they are no Tab stops.
    harness.key_press(egui::Key::Tab);
    harness.run();
    assert_eq!(harness.ctx.memory(|m| m.focused()), None);
    // A screen reader presses them.
    harness.get_by_label("Fermer").click_accesskit();
    harness.run();
    assert!(*harness.state(), "Close asks the app");
}
