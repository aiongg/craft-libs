//! Component dumps of the controls: each control's resolved style (its pure `style` function) for
//! every variant and size its stories show, in every built-in and mode it has, at the Compact size
//! and standard contrast, as text under `tests/dumps/components/`. Rewrite with
//! `UPDATE_DUMPS=1 cargo test -p craft-ui --test control_dumps`.

use craft_theme::{Appearance, ButtonVariant, Contrast, ControlSize, Mode, Size, State, States, TextSize, TypeRole, Variants, builtins, resolve};
use craft_ui::controls::{Button, IconButton, Link, Segmented, Slider, ToggleButton};
use craft_ui::primitives::{SurfaceEdge, SurfaceKind, SurfaceStyle};
use craft_ui::testing::dump::Dump;
use craft_ui::theme::{FontFamilies, UiTokens};
use egui::Color32;

const HEADER: &str = "Generated by crates/ui/tests/control_dumps.rs; rewrite with UPDATE_DUMPS=1 cargo test -p craft-ui --test control_dumps";

const SIZES: [(ControlSize, &str); 2] = [(ControlSize::Sm, "sm"), (ControlSize::Md, "md")];

/// Every built-in in each mode it has, as (`<theme>.<mode>`, tokens).
fn appearances() -> Vec<(String, UiTokens)> {
    let mut out = Vec::new();
    for theme in builtins() {
        let modes = match theme.variants {
            Variants::Both => &[Mode::Light, Mode::Dark][..],
            Variants::LightOnly => &[Mode::Light],
            Variants::DarkOnly => &[Mode::Dark],
        };
        for &mode in modes {
            let appearance =
                Appearance { mode, contrast: Contrast::Standard, size: Size::Compact, text_size: TextSize::default(), reduced_motion: false };
            let tokens = resolve(theme, appearance, None).tokens;
            let id = theme.id.as_str();
            let name = id.strip_prefix("craft.").unwrap_or(id);
            let mode_name = if mode == Mode::Light { "light" } else { "dark" };
            out.push((format!("{name}.{mode_name}"), UiTokens::new(tokens, appearance, mode, FontFamilies::default())));
        }
    }
    out
}

fn check(file: &str, mut each: impl FnMut(&mut Dump, &UiTokens)) {
    let mut dump = Dump::new();
    dump.comment(HEADER);
    for (name, tokens) in appearances() {
        dump.group(&name, |d| each(d, &tokens));
    }
    dump.check(format!("{}/tests/dumps/components/{file}", env!("CARGO_MANIFEST_DIR")));
}

fn states(d: &mut Dump, key: &str, colors: &States<Color32>) {
    for state in State::ALL {
        d.line(&format!("{key}.{}", state.name()), colors.get(state));
    }
}

fn role(role: TypeRole) -> &'static str {
    match role {
        TypeRole::Caption => "caption",
        TypeRole::Label => "label",
        TypeRole::Body => "body",
        TypeRole::BodyStrong => "body_strong",
        TypeRole::Title => "title",
        TypeRole::Heading => "heading",
        TypeRole::Mono => "mono",
    }
}

fn surface(d: &mut Dump, key: &str, s: &SurfaceStyle) {
    d.line(&format!("{key}.fill"), s.fill).line(&format!("{key}.radius"), s.radius);
    match s.edge {
        SurfaceEdge::None => d.line(&format!("{key}.edge"), "none"),
        SurfaceEdge::Border(stroke) => d.line(&format!("{key}.edge.border"), stroke),
        SurfaceEdge::Bevel { top_left, bottom_right, width } => d
            .line(&format!("{key}.edge.bevel.top_left"), top_left)
            .line(&format!("{key}.edge.bevel.bottom_right"), bottom_right)
            .line(&format!("{key}.edge.bevel.width"), width),
        other => d.line(&format!("{key}.edge"), format!("{other:?}")),
    };
}

#[test]
fn button() {
    check("button.txt", |d, t| {
        for (size, name) in SIZES {
            let s = Button::style(t, ButtonVariant::Secondary, size);
            d.group(&format!("size.{name}"), |d| {
                d.line("height", s.height).line("pad_x", s.pad_x).line("gap", s.gap).line("icon", s.icon).line("label", role(s.label));
            });
        }
        d.line("radius", Button::style(t, ButtonVariant::Secondary, ControlSize::Md).radius);
        for variant in ButtonVariant::ALL {
            let s = Button::style(t, variant, ControlSize::Md);
            d.group(variant.name(), |d| {
                d.line("surface", s.surface.map_or("none", SurfaceKind::name));
                states(d, "fill", &s.fill);
                states(d, "border", &s.border);
                states(d, "text", &s.text);
            });
        }
    });
}

