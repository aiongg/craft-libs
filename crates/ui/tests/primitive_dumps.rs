//! Component dumps of the primitives: each primitive's resolved style (its pure `style`
//! function) for every property its stories show, in every built-in and mode it has, at the
//! Compact size and standard contrast, as text under `tests/dumps/components/`. Rewrite with
//! `UPDATE_DUMPS=1 cargo test -p craft-ui --test primitive_dumps`.
//!
//! `Interactive` has no file: it draws its `StateLayer` and `FocusRing`, dumped in theirs.

use craft_theme::{Appearance, Contrast, Mode, Size, TextSize, TypeRole, Variants, builtins, resolve};
use craft_ui::icons::IconSize;
use craft_ui::primitives::{Content, Divider, FocusRing, Gap, Handle, HandleShape, Icon, Pad, StateLayer, Surface, SurfaceEdge, SurfaceKind, Text};
use craft_ui::testing::dump::Dump;
use craft_ui::theme::{FontFamilies, UiTokens};

const HEADER: &str = "Generated by crates/ui/tests/primitive_dumps.rs; rewrite with UPDATE_DUMPS=1 cargo test -p craft-ui --test primitive_dumps";

const ROLES: [(TypeRole, &str); 7] = [
    (TypeRole::Caption, "caption"),
    (TypeRole::Label, "label"),
    (TypeRole::Body, "body"),
    (TypeRole::BodyStrong, "body_strong"),
    (TypeRole::Title, "title"),
    (TypeRole::Heading, "heading"),
    (TypeRole::Mono, "mono"),
];

/// Every built-in in each mode it has, as (`<theme>.<mode>`, tokens).
fn appearances() -> Vec<(String, UiTokens)> {
    let mut out = Vec::new();
    for theme in builtins() {
        let modes = match theme.variants {
            Variants::Both => &[Mode::Light, Mode::Dark][..],
            Variants::LightOnly => &[Mode::Light],
            Variants::DarkOnly => &[Mode::Dark],
        };
        for &mode in modes {
            let appearance =
                Appearance { mode, contrast: Contrast::Standard, size: Size::Compact, text_size: TextSize::default(), reduced_motion: false };
            let tokens = resolve(theme, appearance, None).tokens;
            let id = theme.id.as_str();
            let name = id.strip_prefix("craft.").unwrap_or(id);
            let mode_name = if mode == Mode::Light { "light" } else { "dark" };
            out.push((format!("{name}.{mode_name}"), UiTokens::new(tokens, appearance, mode, FontFamilies::default())));
        }
    }
    out
}

fn check(file: &str, mut each: impl FnMut(&mut Dump, &UiTokens)) {
    let mut dump = Dump::new();
    dump.comment(HEADER);
    for (name, tokens) in appearances() {
        dump.group(&name, |d| each(d, &tokens));
    }
    dump.check(format!("{}/tests/dumps/components/{file}", env!("CARGO_MANIFEST_DIR")));
}

#[test]
fn surface() {
    check("surface.txt", |d, t| {
        for &kind in SurfaceKind::ALL {
            let s = Surface::style(t, kind);
            d.group(kind.name(), |d| {
                d.line("fill", s.fill).line("radius", s.radius).line("shadow", s.shadow);
                match s.edge {
                    SurfaceEdge::None => d.line("edge", "none"),
                    SurfaceEdge::Border(stroke) => d.line("edge.border", stroke),
                    SurfaceEdge::Bevel { top_left, bottom_right, width } => {
                        d.line("edge.bevel.top_left", top_left).line("edge.bevel.bottom_right", bottom_right).line("edge.bevel.width", width)
                    }
                    other => d.line("edge", format!("{other:?}")),
                };
            });
        }
    });
}

